def _try_import(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None:
        return None
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def _resolve_module_constants(tree: ast.Module) -> dict[str, int]:
    """Resolve `N_TRIALS = 20`-style top-level integer assignments."""
    out: dict[str, int] = {}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, int)
        ):
            out[node.targets[0].id] = node.value.value
    return out


def _count_parametrize_trials() -> dict[str, int]:
    """Count trials in test_sigkill_reassignment.py by parsing parametrize."""
    p = TESTS / "test_sigkill_reassignment.py"
    tree = ast.parse(p.read_text())
    consts = _resolve_module_constants(tree)

    def _int_from_expr(expr: ast.expr) -> int | None:
        if isinstance(expr, ast.Constant) and isinstance(expr.value, int):
            return int(expr.value)
        if isinstance(expr, ast.Name) and expr.id in consts:
            return consts[expr.id]
        return None

    counts: dict[str, int] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        for dec in node.decorator_list:
            # @pytest.mark.parametrize("trial", list(range(N)))
            if (
                isinstance(dec, ast.Call)
                and getattr(dec.func, "attr", "") == "parametrize"
                and len(dec.args) >= 2
            ):
                vals = dec.args[1]
                if (
                    isinstance(vals, ast.Call)
                    and getattr(vals.func, "id", "") == "list"
                    and vals.args
                ):
                    inner = vals.args[0]
                    if (
                        isinstance(inner, ast.Call)
                        and getattr(inner.func, "id", "") == "range"
                        and inner.args
                    ):
                        n = _int_from_expr(inner.args[0])
                        if n is not None:
                            counts[node.name] = n
    return counts


def _count_mutation_style_tests() -> int:
    """Count tests with D2-NN mapping in tests/runtimes/multi_agent/test_mutations."""
    p = TESTS / "test_mutations.py"
    if not p.exists():
        return 0
    tree = ast.parse(p.read_text())
    return sum(
        1 for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name.startswith("test_")
    )


def _count_tests_per_file() -> dict[str, int]:
    out: dict[str, int] = {}
    for p in sorted(TESTS.glob("test_*.py")):
        tree = ast.parse(p.read_text())
        n = sum(
            1
            for nn in ast.walk(tree)
            if isinstance(nn, ast.FunctionDef) and nn.name.startswith("test_")
        )
        out[p.name] = n
    return out


def _run(cmd: list[str], *, timeout: float = 60.0) -> dict:
    t0 = time.time()
    # Make repo-root importable as `tests` and `src` as a package base.
    extra_path = os.pathsep.join([str(REPO), str(REPO / "src")])
    existing = os.environ.get("PYTHONPATH", "")
    new_path = f"{extra_path}{os.pathsep}{existing}" if existing else extra_path
    try:
        r = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=str(REPO),
            env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1", "PYTHONPATH": new_path},
        )
        return {
            "cmd": " ".join(cmd),
            "exit_code": r.returncode,
            "stdout_tail": (r.stdout or "")[-1500:],
            "stderr_tail": (r.stderr or "")[-800:],
            "duration_s": round(time.time() - t0, 2),
        }
    except subprocess.TimeoutExpired:
        return {
            "cmd": " ".join(cmd),
            "exit_code": -1,
            "stdout_tail": "",
            "stderr_tail": "",
            "duration_s": round(time.time() - t0, 2),
            "timed_out": True,
        }


