def _perf_sample() -> dict:
    """A fast self-sample to prove the generator actually ran scheduler code."""
    t0 = time.time()
    import sys

    sys.path.insert(0, str(REPO))
    sys.path.insert(0, str(REPO / "src"))
    from tests.runtimes.multi_agent.helpers import FakeVPG, fake_scheduler

    n_agents = 50
    n_tasks = 200
    agents = {
        f"a{i:03d}": {
            "supported_task_kinds": ("*",),
            "specializations": (f"s{i % 5}",),
            "cost_weight": 50 + (i % 10) * 10,
        }
        for i in range(n_agents)
    }
    vpg = FakeVPG()
    sch = fake_scheduler(agents, fake_vpg=vpg)
    for i in range(n_tasks):
        vpg.add_ready_task(f"t{i:04d}", required_specializations=(f"s{i % 5}",))
    t_prep = time.time() - t0
    t1 = time.time()
    rounds = 0
    dispatched = 0
    frontier = vpg.ready_frontier(vpg.graph_id)
    while frontier and rounds < 1000:
        res = sch.schedule_once(vpg.graph_id)
        dispatched += len(res.dispatched)
        frontier = vpg.ready_frontier(vpg.graph_id)
        rounds += 1
        if not res.dispatched and not res.skipped:
            break
    t_run = time.time() - t1
    return {
        "prep_s": round(t_prep, 4),
        "run_s": round(t_run, 4),
        "rounds": rounds,
        "total_dispatched": dispatched,
        "per_round_ms": round(t_run / max(rounds, 1) * 1000, 3),
        "sample_ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
    }


